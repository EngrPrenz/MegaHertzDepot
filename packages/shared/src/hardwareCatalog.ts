export function getDefaultCatalogImageUrl(sku?: string | null, name?: string | null): string | undefined {
  if (sku) {
    const normalized = sku.trim().toUpperCase();
    const matchBySku = SAMPLE_PC_HARDWARE_CATALOG.find(
      (item) => item.sku.toUpperCase() === normalized
    );
    if (matchBySku?.imageUrl) return matchBySku.imageUrl;
  }
  if (name) {
    const normalizedName = name.trim().toLowerCase();
    const matchByName = SAMPLE_PC_HARDWARE_CATALOG.find(
      (item) => item.name.toLowerCase() === normalizedName
    );
    if (matchByName?.imageUrl) return matchByName.imageUrl;
  }
  return undefined;
}

export interface PcBuildCompatibilityReport {
  isCompatible: boolean;
  errors: string[];
  warnings: string[];
  estimatedSystemWatts: number;
  recommendedPsuWatts: number;
  selectedPsuWatts: number | null;
}

export type PcBuildSlotPart =
  | Pick<Product, 'name' | 'category' | 'specs'>
  | Array<Pick<Product, 'name' | 'category' | 'specs'>>;

/**
 * Evaluates socket compatibility, RAM generation match, and PSU wattage headroom
 * for a selected set of PC Rig Builder parts (supports multiple parts per slot, e.g. CPU Cooler + Case Fans, or multiple SSDs).
 */
export function analyzePcBuildCompatibility(
  selectedParts: Partial<Record<HardwareCategory, PcBuildSlotPart>>
): PcBuildCompatibilityReport {
  const errors: string[] = [];
  const warnings: string[] = [];

  const firstOf = (slot?: PcBuildSlotPart) => (Array.isArray(slot) ? slot[0] : slot);
  const listOf = (slot?: PcBuildSlotPart) =>
    !slot ? [] : Array.isArray(slot) ? slot : [slot];

  const cpu = firstOf(selectedParts.CPU);
  const mobo = firstOf(selectedParts.Motherboard);
  const ramList = listOf(selectedParts.RAM);
  const psu = firstOf(selectedParts.PSU);

  // 1. CPU <-> Motherboard Socket Check
  if (cpu?.specs?.socket && mobo?.specs?.socket) {
    if (cpu.specs.socket.toUpperCase() !== mobo.specs.socket.toUpperCase()) {
      errors.push(
        `Socket Mismatch: ${cpu.name} uses ${cpu.specs.socket}, but ${mobo.name} uses ${mobo.specs.socket}.`
      );
    }
  }

  // 2. Motherboard <-> RAM Generation Check
  if (mobo?.specs?.ramType) {
    for (const ram of ramList) {
      if (ram?.specs?.ramType) {
        if (mobo.specs.ramType.toUpperCase() !== ram.specs.ramType.toUpperCase()) {
          errors.push(
            `Memory Type Mismatch: ${mobo.name} requires ${mobo.specs.ramType}, but ${ram.name} is ${ram.specs.ramType}.`
          );
        }
      }
    }
  }

  // 3. Calculate Estimated Component Wattage (excluding PSU, Monitor, and Laptop)
  let estimatedSystemWatts = 0;
  for (const [cat, slotValue] of Object.entries(selectedParts)) {
    if (!slotValue || cat === 'PSU' || cat === 'Monitor' || cat === 'Laptop') continue;
    for (const part of listOf(slotValue)) {
      if (part?.specs?.wattage && part.specs.wattage > 0) {
        estimatedSystemWatts += part.specs.wattage;
      }
    }
  }

  const recommendedPsuWatts =
    estimatedSystemWatts > 0 ? Math.ceil((estimatedSystemWatts * 1.25) / 50) * 50 : 0;
  const selectedPsuWatts = psu?.specs?.wattage ?? null;

  if (selectedPsuWatts !== null && estimatedSystemWatts > 0) {
    if (selectedPsuWatts < estimatedSystemWatts) {
      errors.push(
        `Insufficient Power Supply: Selected PSU (${selectedPsuWatts}W) is below estimated system load (${estimatedSystemWatts}W).`
      );
    } else if (selectedPsuWatts < recommendedPsuWatts) {
      warnings.push(
        `Tight PSU Headroom: Selected PSU is ${selectedPsuWatts}W; we recommend at least ${recommendedPsuWatts}W (25% transient headroom).`
      );
    }
  }

  return {
    isCompatible: errors.length === 0,
    errors,
    warnings,
    estimatedSystemWatts,
    recommendedPsuWatts,
    selectedPsuWatts,
  };
}

